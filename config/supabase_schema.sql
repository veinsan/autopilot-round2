-- Event ledger insert and monotonic command transition are one transaction.
create or replace function public.persist_workflow_event(
  target_command_id text,
  new_event_id text,
  new_source_event_id text,
  new_event_type text,
  new_status text,
  safe_details jsonb,
  resolved_auto_run_id text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  current_status text;
  cancellation_requested timestamptz;
begin
  if new_status not in ('queued', 'running', 'completed', 'failed', 'cancelled') then
    raise exception 'Invalid command status';
  end if;
  select "status", "cancel_requested_at" into current_status, cancellation_requested
    from "command_runs" where "command_id" = target_command_id for update;
  if current_status is null then raise exception 'Command run not found'; end if;
  if current_status in ('completed', 'failed', 'cancelled') then return false; end if;
  if current_status = 'running' and new_status = 'queued' then return false; end if;
  if cancellation_requested is not null and new_status not in ('completed', 'failed', 'cancelled') then
    return false;
  end if;
  insert into "workflow_events" (
    "event_id", "source_event_id", "execution_id", "operator_id",
    "event_type", "status", "details"
  ) values (
    new_event_id, new_source_event_id, target_command_id, 'orchestrator',
    new_event_type, new_status, safe_details
  ) on conflict ("event_id") do nothing;
  update "command_runs" set
    "status" = new_status,
    "auto_run_id" = coalesce(resolved_auto_run_id, "auto_run_id"),
    "last_event_at" = now(),
    "reconciliation_status" = case
      when new_status in ('completed', 'failed', 'cancelled') then 'complete'
      else 'pending'
    end
  where "command_id" = target_command_id;
  return true;
end;
$$;
revoke all on function public.persist_workflow_event(text, text, text, text, text, jsonb, text) from public, anon, authenticated;
grant execute on function public.persist_workflow_event(text, text, text, text, text, jsonb, text) to service_role;

create or replace function public.claim_reconciliation_lease(
  lease_owner text,
  lease_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  claimed boolean;
begin
  if lease_seconds < 15 or lease_seconds > 3600 then
    raise exception 'Invalid reconciliation lease duration';
  end if;
  insert into "reconciliation_leases" ("lease_key", "lease_owner", "lease_until")
    values ('auto_runs', lease_owner, now() + make_interval(secs => lease_seconds))
  on conflict ("lease_key") do update set
    "lease_owner" = excluded."lease_owner",
    "lease_until" = excluded."lease_until",
    "updated_at" = now()
  where "reconciliation_leases"."lease_until" <= now()
     or "reconciliation_leases"."lease_owner" = excluded."lease_owner"
  returning true into claimed;
  return coalesce(claimed, false);
end;
$$;
revoke all on function public.claim_reconciliation_lease(text, integer) from public, anon, authenticated;
grant execute on function public.claim_reconciliation_lease(text, integer) to service_role;

-- Case mutation and its audit entry are one transaction. The function exposes
-- no confidential payload and rejects nonexistent cases or invalid transitions.
create or replace function public.record_case_action(
  target_case_id text,
  case_table text,
  actor_subject text,
  action_decision text,
  safe_feedback text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  current_status text;
  current_assignee text;
  next_status text;
  resolution_identifier text := 'res_' || replace(gen_random_uuid()::text, '-', '');
begin
  if action_decision not in ('claim', 'acknowledge', 'await_external_update', 'resolve') then
    raise exception 'Unsupported case action';
  end if;
  if case_table = 'standard' then
    select "status", "assigned_to" into current_status, current_assignee
      from "workbench_cases" where "case_id" = target_case_id for update;
  elsif case_table = 'confidential' then
    select "status" into current_status from "Confidential_Cases" where "case_id" = target_case_id for update;
  else
    raise exception 'Unsupported case table';
  end if;
  if current_status is null then raise exception 'Case not found'; end if;
  if current_status = 'resolved' then raise exception 'Resolved case cannot be changed'; end if;
  if action_decision = 'claim' and current_status <> 'open' then
    raise exception 'Only an open case can be claimed';
  end if;
  if action_decision in ('acknowledge', 'await_external_update') and current_status <> 'in_review' then
    raise exception 'Case must be in review for this action';
  end if;
  if action_decision = 'resolve' and current_status not in ('in_review', 'awaiting_external_update') then
    raise exception 'Case must be reviewed before resolution';
  end if;
  if case_table = 'standard' and action_decision <> 'claim'
     and current_assignee is not null and current_assignee <> actor_subject then
    raise exception 'Case is assigned to another actor';
  end if;

  next_status := case action_decision
    when 'claim' then 'in_review'
    when 'await_external_update' then 'awaiting_external_update'
    when 'resolve' then 'resolved'
    else current_status
  end;
  if case_table = 'standard' then
    update "workbench_cases"
      set "status" = next_status,
          "assigned_to" = case when action_decision = 'claim' then actor_subject else "assigned_to" end,
          "resolved_at" = case when action_decision = 'resolve' then now() else null end
      where "case_id" = target_case_id;
  else
    update "Confidential_Cases"
      set "status" = next_status,
          "resolved_at" = case when action_decision = 'resolve' then now() else null end
      where "case_id" = target_case_id;
  end if;
  insert into "case_resolutions" ("resolution_id", "case_id", "resolved_by", "decision", "sanitized_feedback")
    values (resolution_identifier, target_case_id, actor_subject, action_decision, safe_feedback);
  return next_status;
end;
$$;
