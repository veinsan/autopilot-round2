-- Approval insertion and lifecycle transition are atomic. Confidential-routing
-- policies stay simulated until two independent approvers cover both roles.
create or replace function public.record_policy_approval(
  target_version_id text,
  actor_subject text,
  actor_role text,
  approval_decision text,
  approval_note text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  current_status text;
  confidential boolean;
  admin_count integer;
  confidential_count integer;
  distinct_count integer;
begin
  if actor_role not in ('admin', 'people_ops_confidential') or approval_decision not in ('approve', 'reject') then
    raise exception 'Invalid policy approval';
  end if;
  select "status", "is_confidential_routing" into current_status, confidential
    from "policy_versions" where "version_id" = target_version_id for update;
  if current_status is null then raise exception 'Policy version not found'; end if;
  if current_status <> 'simulated' then raise exception 'Policy must be simulated before approval'; end if;

  insert into "policy_approvals" ("approval_id", "version_id", "approved_by", "approver_role", "decision", "note")
    values ('approval_' || replace(gen_random_uuid()::text, '-', ''), target_version_id, actor_subject, actor_role, approval_decision, approval_note)
    on conflict ("version_id", "approved_by", "approver_role")
    do update set "decision" = excluded."decision", "note" = excluded."note", "created_at" = now();
  if approval_decision = 'reject' then return 'simulated'; end if;

  select
    count(*) filter (where "approver_role" = 'admin' and "decision" = 'approve'),
    count(*) filter (where "approver_role" = 'people_ops_confidential' and "decision" = 'approve'),
    count(distinct "approved_by") filter (where "decision" = 'approve')
  into admin_count, confidential_count, distinct_count
  from "policy_approvals" where "version_id" = target_version_id;
  if admin_count > 0 and (not confidential or (confidential_count > 0 and distinct_count > 1)) then
    update "policy_versions" set "status" = 'approved', "approved_at" = now() where "version_id" = target_version_id;
    return 'approved';
  end if;
  return 'simulated';
end;
$$;
revoke all on function public.record_policy_approval(text, text, text, text, text) from public, anon, authenticated;
grant execute on function public.record_policy_approval(text, text, text, text, text) to service_role;

-- Atomic activation prevents operators observing a partially updated policy.
create or replace function public.activate_policy_version(target_version_id text, actor_subject text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (select 1 from "policy_versions" where "version_id" = target_version_id and "status" = 'approved') then
    raise exception 'Policy version must exist and be approved before activation';
  end if;
  if not exists (select 1 from "policy_simulations" where "version_id" = target_version_id) then
    raise exception 'Policy version must be simulated before activation';
  end if;
  update "policy_versions" set "status" = 'retired' where "status" = 'active';
  update "policy_versions" set "status" = 'active', "activated_at" = now() where "version_id" = target_version_id;
  insert into "policy_evaluations" (
    "evaluation_id", "policy_version_id", "policy_key", "outcome", "action", "evidence"
  ) values (
    'evaluation_' || replace(gen_random_uuid()::text, '-', ''),
    target_version_id, 'POLICY_ACTIVATION', 'active', 'activated',
    jsonb_build_object('actor_subject', actor_subject)
  );
end;
$$;
revoke all on function public.activate_policy_version(text, text) from public, anon, authenticated;
grant execute on function public.activate_policy_version(text, text) to service_role;

